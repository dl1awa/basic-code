package com.dl1_.loopfor;

public class fordemo2 {
    public static void main(String[] args) {
        for(int a = 1; a <=5; a++){
            System.out.print(a + " ");
        }
        System.out.println(" ");
        //fordemo3 5-1
        for(int b = 5;b >=1;b--){
            System.out.print(b + " ");
        }
    }
}
